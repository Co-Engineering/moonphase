def test_a_command_that_exits_non_zero_is_a_failure_though_agy_says_done() -> None:
    """agy records the step as "DONE" — the command ran — and only its TUI
    says 'failed'; the exit code on the result's first line is the tell."""
    (failed,) = _events(DRIVEN, 17)
    assert failed.ok is False
