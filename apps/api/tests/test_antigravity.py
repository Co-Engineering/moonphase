"""The Antigravity harness, held to what the real `agy` 1.4.3 binary does.

Every fixture under `fixtures/antigravity/` came from the shipped 1.4.3 binary
run in an isolated HOME, with no Google account anywhere near it: the TUI was
driven in tmux in its documented Gemini API key mode, with a fake key and
`GOOGLE_GEMINI_BASE_URL` pointing at a local stand-in for the Gemini API that
scripted the model's replies (an edit, a failing tool, a declined command, a
reply with thinking and two tool calls, an ask_question picker, a slow reply)
and logged exactly what agy sent it. The signed-out screens were captured the
same way with no key at all and every outbound connection refused, so the
sign-in URL was printed but never visited. Absolute scratch paths were
rewritten to `/workspace` (the working directory) and `/home/dev` (the HOME),
the shapes a session uses, and a path agy had wrapped across two lines became
one; nothing else was edited.

What was checked against the binary, and is pinned here:

* The files this harness writes into a session HOME, generated by its own
  methods, are accepted: `agy mcp list` shows both kinds of MCP server with
  the right transport, nothing in its log calls the settings invalid, the
  instructions reach the model as its `user_global` rule, and the skill is
  listed in the system prompt and offered as a slash command.
* The API-key path engages from the merged settings file, and switching the
  same HOME to a Google sign-in takes `modelProvider` out again, which puts
  agy back on its sign-in screen with the folder-trust decisions kept.
* A planted consumer token is loaded by a new process; an empty token file —
  how a previous account's sign-in is forgotten — reads as signed out and
  does not get in the way of API-key mode.
* The transcript, the live-transcript lookup, the prompts, the panes and the
  sign-in URL, each below.
"""

