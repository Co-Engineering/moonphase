def test_nothing_this_harness_writes_is_ever_empty(profile: WorkspaceProfile) -> None:
    """profile.write_file feeds the contents to `cat` over asyncssh, which
    sends no end-of-file for an empty string (shown against a local asyncssh
    server: "hello" and "\\n" arrive, "" waits until the timeout), so an
    empty file would hang session start for a minute and then fail it."""
    written = list(AGY.profile_files(profile, SPACE).values())
    if profile.harness_credential is not None:
        written += AGY.credential_files(profile.harness_credential, SPACE).values()
    for existing in (None, "{}", json.dumps({"modelProvider": "gemini"})):
        merged = AGY.merge_into_profile_file(existing, profile)
        if merged is not None:
            written.append(merged)
    for keep in (True, False):
        merged = AGY.merge_into_credentials_file(TOKEN, {}, keep_account_login=keep)
        if merged is not None:
            written.append(merged)
    assert all(contents for contents in written)


