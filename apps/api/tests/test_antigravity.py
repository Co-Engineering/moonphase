def test_a_user_turn_is_what_was_typed_without_agys_own_additions() -> None:
    """agy wraps the prompt in <USER_REQUEST> and adds the time and any
    changed setting after it; those are for the model, not the reader."""
    (event,) = _events(EARLIER, 0)
    assert (event.kind, event.text) == ("user", "write hello")
    (event,) = _events(DRIVEN, 0)
