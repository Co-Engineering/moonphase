def test_every_real_transcript_line_parses_into_events_the_api_accepts() -> None:
    """82 real steps from six conversations: none raises, every event
    validates as the polling API's `TranscriptEventOut` with an aware
    timestamp, and no id repeats across conversations — step indexes restart
    in each one, and the feed de-duplicates by id across a switch."""
    seen: set[str] = set()
    records = 0
    for conversation, lines in _conversations().items():
        for record in lines:
            records += 1
            for event in AGY.parse_transcript_record(record, _source(conversation)):
                assert event.id not in seen, event.id
                seen.add(event.id)
                out = TranscriptEventOut.model_validate(event.to_dict())
                assert isinstance(out.at, datetime) and out.at.tzinfo is not None
    assert records == 82
    assert len(seen) > records


