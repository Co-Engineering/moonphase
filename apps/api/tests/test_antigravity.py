def test_a_gemini_key_adds_model_provider_and_keeps_everything_agy_wrote() -> None:
    """GEMINI_API_KEY alone leaves agy on its sign-in screen; it also needs
    `"modelProvider": "gemini"`. The file is agy's own — it records folder
    trust there — so the key is merged in, never the file replaced."""
    existing = json.dumps({"trustedWorkspaces": ["/workspace"], "colorScheme": "dark"})
    merged = json.loads(AGY.merge_into_profile_file(existing, _profile()) or "")
    assert merged == {
        "trustedWorkspaces": ["/workspace"],
        "colorScheme": "dark",
        "modelProvider": "gemini",
    }
    assert json.loads(AGY.merge_into_profile_file(None, _profile()) or "") == {
        "modelProvider": "gemini"
    }


def test_a_google_sign_in_takes_out_only_the_gemini_provider() -> None:
    """Left in place after a move to a Google account it would go on asking
    for a key that is no longer there. Taken out, agy was back on its sign-in
    screen with the trust decisions intact."""
    existing = json.dumps({"modelProvider": "gemini", "trustedWorkspaces": ["/workspace"]})
    merged = AGY.merge_into_profile_file(existing, _profile(harness_credential=_oauth()))
    assert json.loads(merged or "") == {"trustedWorkspaces": ["/workspace"]}
    # A value Moonphase never writes is not Moonphase's to remove.
    other = json.dumps({"modelProvider": "something-else"})
    assert AGY.merge_into_profile_file(other, _profile(harness_credential=_oauth())) is None


def test_an_unreadable_settings_file_is_left_exactly_as_it_is() -> None:
    """agy ignores a settings file it cannot read but keeps it on disk;
    overwriting it for one key would lose whatever else is in it."""
    for existing in ("{not json", "[1, 2]", '"text"'):
        assert AGY.merge_into_profile_file(existing, _profile()) is None
        assert AGY.merge_into_profile_file(existing, _profile(harness_credential=_oauth())) is None


def test_nothing_is_written_when_there_is_nothing_to_change() -> None:
    """No file is created just to hold nothing, and one already right is not
    rewritten on every start."""
    assert AGY.merge_into_profile_file(None, _profile(harness_credential=_oauth())) is None
    assert AGY.merge_into_profile_file(None, _profile(harness_credential=None)) is None
    already = json.dumps({"modelProvider": "gemini", "trustedWorkspaces": ["/workspace"]})
    assert AGY.merge_into_profile_file(already, _profile()) is None
    plain = json.dumps({"trustedWorkspaces": ["/workspace"]})
    assert AGY.merge_into_profile_file(plain, _profile(harness_credential=_oauth())) is None


# --- forgetting a sign-in -------------------------------------------------------


def test_a_previous_sign_in_is_forgotten_only_when_the_session_moved_off_it() -> None:
    """A token file holding `{}` reads as signed out ('unknown auth method',
    then the sign-in picker) and did not stop a session on a key reaching
    the API; so did an empty one, but an empty write never finishes (see
    above). Moving to a key overwrites the sign-in; a session still on it, a
    missing file, or one already forgotten is left alone."""
    assert AGY.merge_into_credentials_file(TOKEN, {}, keep_account_login=False) == "{}\n"
    assert AGY.merge_into_credentials_file(TOKEN, {}, keep_account_login=True) is None
    assert AGY.merge_into_credentials_file(None, {}, keep_account_login=False) is None
    assert AGY.merge_into_credentials_file("", {}, keep_account_login=False) is None
    assert AGY.merge_into_credentials_file("{}\n", {}, keep_account_login=False) is None
    assert AGY.merge_into_credentials_file(TOKEN, {"srv": "{}"}, keep_account_login=True) is None


@pytest.mark.skipif(shutil.which("sh") is None, reason="needs a POSIX sh")
def test_the_auth_probe_agrees_with_agy_about_who_is_signed_in(tmp_path: Path) -> None:
    """The same rule agy applies: a forgotten (`{}`) or empty file is no
    sign-in; a real token, or a key, is."""
    space = SessionSpace(home=str(tmp_path), workdir=str(tmp_path / "work"))
    token = tmp_path / ".gemini" / "antigravity-cli" / "antigravity-oauth-token"
    probe = AGY.auth_probe_script(space)

    def signed_in(**env: str) -> bool:
        run = subprocess.run(["sh", "-c", probe], env={"PATH": "/usr/bin:/bin", **env})
        return run.returncode == 0

    assert not signed_in()
    token.parent.mkdir(parents=True)
    forgot = AGY.merge_into_credentials_file(TOKEN, {}, keep_account_login=False)
    for forgotten in ("", "{}\n", forgot or ""):
        token.write_text(forgotten)
        assert not signed_in()
        assert signed_in(GEMINI_API_KEY="fake-gemini-key")
    token.write_text(TOKEN)
    assert signed_in()


