needs_sh_and_jq = pytest.mark.skipif(
    shutil.which("sh") is None or shutil.which("jq") is None, reason="needs sh and jq"
)


def _home(tmp_path: Path, mapping: object, conversation: str | None = DRIVEN) -> SessionSpace:
    """A HOME laid out the way agy left the probe's, keyed by the workdir."""
    space = SessionSpace(home=str(tmp_path / "home"), workdir=str(tmp_path / "work dir"))
    app = Path(space.home) / ".gemini" / "antigravity-cli"
    (app / "cache").mkdir(parents=True)
    (app / "cache" / "last_conversations.json").write_text(
        mapping if isinstance(mapping, str) else json.dumps(mapping)
    )
    if conversation:
        logs = app / "brain" / conversation / ".system_generated" / "logs"
        logs.mkdir(parents=True)
        (logs / "transcript_full.jsonl").write_text("{}\n")
    return space


def _live(space: SessionSpace, path: str = "/usr/bin:/bin", sh: str = "sh"):
    return subprocess.run(
        [sh, "-c", AGY.live_transcript_script(space)],
        env={"PATH": path},
        cwd=Path(space.home).parent,
        capture_output=True,
        text=True,
    )


@needs_sh_and_jq
def test_the_live_transcript_is_the_conversation_agy_would_continue_here(tmp_path: Path) -> None:
    """agy's own map from working directory to conversation, so another
    worktree's conversation in the same HOME is never followed — and a
    workdir with a space in it is quoted."""
    space = _home(tmp_path, {str(tmp_path / "work dir"): DRIVEN, "/elsewhere": "other-id"})
    run = _live(space)
    assert run.returncode == 0 and run.stderr == ""
    assert run.stdout == (
        f"{space.home}/.gemini/antigravity-cli/brain/{DRIVEN}"
        "/.system_generated/logs/transcript_full.jsonl\n"
    )
    transcript_dir = AGY.transcript_dir(space)
    assert run.stdout.strip().startswith(transcript_dir + "/")


